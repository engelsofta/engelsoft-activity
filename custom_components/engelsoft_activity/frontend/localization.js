export function activityLocale(hass) {
  return hass?.locale?.language || hass?.language || 'de';
}

export function activityLanguage(locale) {
  return /^de(?:-|$)/i.test(locale) ? 'de' : 'en';
}

export function activityTranslator(locale) {
  const german = activityLanguage(locale) === 'de';
  return (message, values) => {
    const text = german || !Object.hasOwn(english, message) ? message : english[message];
    return values ? text.replace(/\{\{(\w+)\}\}/g, (_, key) => String(values[key] ?? '')) : text;
  };
}

const numbers = new Map();

export function activityNumber(locale, value, maximumSignificantDigits) {
  const key = JSON.stringify([locale, maximumSignificantDigits]);
  if (!numbers.has(key)) {
    numbers.set(key, new Intl.NumberFormat(locale, { maximumSignificantDigits }));
  }
  return numbers.get(key).format(value);
}
